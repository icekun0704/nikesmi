#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""js/specials/*.js を連結して js/specials.js を作る.

    python -I tools/build_specials.py

各ファイルは独立していて、次の形で自分のキャラだけを登録する:

    (window.SPECIALS = window.SPECIALS || {})[<id>] = { init, tick, onShot, onBurst };

ファイル名は <id>.js（宝物版は <id>star.js）。同じ id を二重に登録したら失敗する。
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SRC = os.path.join(APP, 'js', 'specials')
OUT = os.path.join(APP, 'js', 'specials.js')


def main():
    if not os.path.isdir(SRC):
        raise SystemExit('no js/specials directory')
    files = sorted(f for f in os.listdir(SRC) if f.endswith('.js'))
    parts = ['/* generated by tools/build_specials.py — do not edit by hand */',
             'window.SPECIALS = window.SPECIALS || {};', '']
    seen = {}
    for f in files:
        path = os.path.join(SRC, f)
        text = io.open(path, encoding='utf-8').read()
        ids = re.findall(r'SPECIALS\s*=\s*window\.SPECIALS\s*\|\|\s*\{\}\)\[(\d+)\]', text)
        ids += re.findall(r'window\.SPECIALS\[(\d+)\]', text)
        for i in ids:
            if i in seen:
                raise SystemExit('duplicate special for id %s: %s and %s' % (i, seen[i], f))
            seen[i] = f
        parts.append('/* ---- %s ---- */' % f)
        parts.append(text.rstrip())
        parts.append('')
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(parts))
    print('specials: %d files, %d characters' % (len(files), len(seen)))
    print('ids: ' + ' '.join(sorted(seen, key=int)))


if __name__ == '__main__':
    main()
