# -*- coding: utf-8 -*-
"""
Download character portraits so the roster grid works offline.

Avatars are referenced by work/pvp/characters_core.json as site-relative paths
(`assets/immutable/avatars/characters/<file>`). This script pulls each one into
arena-sim/assets/portraits/ and writes js/portraits.js (id -> relative path).

NOTE: the images are game art. arena-sim/assets/ is git-ignored on purpose;
re-run this script after cloning instead of committing the art.

Run: python -I tools/fetch_portraits.py [--force]
"""
import json, io, os, sys, ssl
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ROOT = os.path.dirname(APP)
CORE = os.path.join(ROOT, 'work', 'pvp', 'characters_core.json')
BASE = 'https://nikke.skyxmoon.cn/'
OUT = os.path.join(APP, 'assets', 'portraits')
INDEX = os.path.join(APP, 'js', 'portraits.js')

FORCE = '--force' in sys.argv


def main():
    with io.open(CORE, 'r', encoding='utf-8') as f:
        chars = json.load(f)['CHARACTERS']

    os.makedirs(OUT, exist_ok=True)
    ctx = ssl.create_default_context()
    mapping = {}
    ok = miss = fail = 0

    for c in chars:
        rel = c.get('avatarUrl') or c.get('standardAvatarUrl')
        if not rel:
            miss += 1
            continue
        name = os.path.basename(rel)
        dst = os.path.join(OUT, name)
        mapping[str(c['id'])] = 'assets/portraits/' + name
        if os.path.exists(dst) and not FORCE:
            ok += 1
            continue
        url = BASE + rel
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=30, context=ctx) as r:
                data = r.read()
            with open(dst, 'wb') as f:
                f.write(data)
            ok += 1
        except Exception as e:
            fail += 1
            mapping.pop(str(c['id']), None)
            if fail <= 5:
                print('fail', url, e)

    js = ('/* generated by tools/fetch_portraits.py — do not edit */\n'
          'window.PORTRAITS = ' + json.dumps(mapping, separators=(',', ':')) + ';\n')
    with io.open(INDEX, 'w', encoding='utf-8') as f:
        f.write(js)

    total = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT)) if os.path.isdir(OUT) else 0
    print('downloaded %d, already had %d, failed %d, no avatar %d' % (ok, 0, fail, miss))
    print('portraits on disk: %d files, %.1f MB' % (len(os.listdir(OUT)), total / 1e6))
    print('wrote', INDEX)


if __name__ == '__main__':
    main()
