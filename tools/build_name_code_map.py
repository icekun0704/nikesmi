# -*- coding: utf-8 -*-
"""
Build data/name_code_map.json — blablalink name_code -> local character ids.

blablalink returns a roster keyed by `name_code`. Our data.js carries the same
code on 176 of 229 rows, but a character that exists in both a base and a
treasure form shares one code, so the importer needs to know both ids.

Output
  { "5007": { "jp": "プリバティ", "base": 137, "treasure": 145 }, ... }

`base`/`treasure` may be null. A code with neither is not written at all.

Run: python -I tools/build_name_code_map.py
"""
import json, io, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)


def load(*parts):
    with io.open(os.path.join(*parts), 'r', encoding='utf-8') as f:
        return json.load(f)


def main():
    src = io.open(os.path.join(APP, 'js', 'data.js'), encoding='utf-8').read()
    chars = json.loads(src.split('window.CHARACTERS = ', 1)[1].rstrip().rstrip(';'))

    mapping = {}
    problems = []
    for c in chars:
        code = c.get('nameCode')
        if not code:
            continue
        entry = mapping.setdefault(str(code), {'jp': c['name'].replace('（宝）', ''),
                                               'base': None, 'treasure': None})
        slot = 'treasure' if c['treasure'] else 'base'
        if entry[slot] is not None:
            problems.append('name_code %s has two %s rows: %s / %s' %
                            (code, slot, entry[slot], c['id']))
            continue
        entry[slot] = c['id']

    # a code that only has a treasure row still needs a base handle
    for code, entry in mapping.items():
        if entry['base'] is None and entry['treasure'] is not None:
            entry['base'] = entry['treasure']

    if problems:
        print('DUPLICATE name_code assignments — the importer would be ambiguous:')
        for p in problems:
            print('  ' + p)
        sys.exit(1)

    # emitted as a plain <script> global: file:// pages cannot fetch() JSON
    dst = os.path.join(APP, 'js', 'name_code_map.js')
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with io.open(dst, 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/build_name_code_map.py — do not edit */\n')
        f.write('window.NAME_CODE_MAP = ' +
                json.dumps(mapping, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')

    both = sum(1 for v in mapping.values() if v['treasure'])
    print('name codes: %d  (with a treasure form: %d)' % (len(mapping), both))
    print('wrote', dst)


if __name__ == '__main__':
    main()
